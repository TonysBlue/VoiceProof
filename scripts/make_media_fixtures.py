"""Derive small local compressed media from committed synthetic Mandarin speech.
Source was generated by eSpeak NG 1.51 cmn-latn-pinyin, speed145; never customer material.
"""
from pathlib import Path
import av
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'tests/fixtures/mandarin-synthetic.wav'
TEXT='今天我们介绍录音技巧。录音时保持环境安静，距离麦克风二十厘米。完成后请仔细检查，再发布作品。'


def convert(target, codec, video=False):
    with av.open(str(SOURCE)) as source, av.open(str(target),'w') as out:
        audio=out.add_stream(codec,rate=24000)
        audio.layout='mono'
        if video:
            visual=out.add_stream('mpeg4',rate=10)
            visual.width=320;visual.height=180;visual.pix_fmt='yuv420p'
            for index in range(200):
                pixels=np.full((180,320,3),(40,74,60),dtype=np.uint8)
                frame=av.VideoFrame.from_ndarray(pixels,format='rgb24');frame.pts=index
                for packet in visual.encode(frame):out.mux(packet)
            for packet in visual.encode():out.mux(packet)
        resampler=av.AudioResampler(format=audio.codec_context.format.name,layout='mono',rate=24000)
        for frame in source.decode(audio=0):
            for chunk in resampler.resample(frame):
                for packet in audio.encode(chunk):out.mux(packet)
        for chunk in resampler.resample(None):
            for packet in audio.encode(chunk):out.mux(packet)
        for packet in audio.encode():out.mux(packet)

if __name__=='__main__':
    output=ROOT/'.tools/fixtures';output.mkdir(parents=True,exist_ok=True)
    for suffix,codec,video in [('mp3','libmp3lame',False),('m4a','aac',False),('mp4','aac',True),('flac','flac',False)]:
        convert(output/('mandarin.'+suffix),codec,video)
        print(suffix)
